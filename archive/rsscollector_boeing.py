# Collect RSS articles

articles = []

for query_name, feed_url in rss_feeds.items():
    feed = feedparser.parse(feed_url)

    for entry in feed.entries:
        title = entry.get("title", "")
        summary = clean_html(entry.get("summary", ""))
        link = entry.get("link", "")
        published = entry.get("published", "")

        text = f"{title} {summary}".lower()

        matched_suppliers = [
            supplier for supplier in suppliers
            if supplier.lower() in text
        ]

        matched_risks = [
            risk for risk in risk_terms
            if risk.lower() in text
        ]

        signal_types = get_risk_categories(text)

        articles.append({
            "query_name": query_name,
            "title": title,
            "published": published,
            "link": link,
            "matched_suppliers": matched_suppliers,
            "matched_risk_terms": matched_risks,
            "signal_types": signal_types,
            "summary": summary
        })

df = pd.DataFrame(articles)

