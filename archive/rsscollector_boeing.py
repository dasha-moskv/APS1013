# Take text input and identifies which predefined risk categories are present
def get_risk_categories(text):
    matched_categories = []

    text = str(text).lower()

    for category, keywords in risk_categories.items():
        for keyword in keywords:
            if keyword.lower() in text:
                matched_categories.append(category)
                break

    return matched_categories

# Count the risks and determine the primary risk
def get_primary_risk_category(matched_terms):

    if not isinstance(matched_terms, list) or len(matched_terms) == 0:
        return "unknown"

    category_counts = {}

    for category, keywords in risk_categories.items():

        count = 0

        for term in matched_terms:
            if term.lower() in [k.lower() for k in keywords]:
                count += 1

        if count > 0:
            category_counts[category] = count

    if len(category_counts) == 0:
        return "unknown"

    return max(category_counts, key=category_counts.get)

# Figure out the primary supplier
def get_primary_supplier(text, matched_suppliers):

    if not matched_suppliers:
        return "Unknown"

    counts = {}

    text = str(text).lower()

    for supplier in matched_suppliers:
        counts[supplier] = text.count(supplier.lower())

    return max(counts, key=counts.get)


def enrich_signal(row):
    matched_suppliers = row.get("matched_suppliers", [])
    matched_terms = row.get("matched_risk_terms", [])

    full_text = f"{row.get('title', '')} {row.get('summary', '')}"

    primary_supplier = get_primary_supplier(
        full_text,
        matched_suppliers
    )

    primary_risk_category = get_primary_risk_category(matched_terms)

    return pd.Series({
        "primary_supplier": primary_supplier,
        "matched_supplier_count": len(matched_suppliers),
        "commodity": suppliers.get(primary_supplier, "Unknown"),
        "primary_risk_category": primary_risk_category,
        "risk_category_tier": risk_category_tiers.get(primary_risk_category, "Unknown")
    })

